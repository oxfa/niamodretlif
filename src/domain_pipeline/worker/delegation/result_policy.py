"""Delegation result-code policy helpers."""

from __future__ import annotations

from typing import Any

from domain_pipeline.worker.delegation.result_codes import (
    PIPELINE_RESULT_CODE_DELEGATION_EXISTS,
    PIPELINE_RESULT_CODE_DELEGATION_NODATA,
    PIPELINE_RESULT_CODE_DELEGATION_NO_NAMESERVERS,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_ABSENT,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_EXISTS,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_SERVFAIL,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_TIMEOUT,
    PIPELINE_RESULT_CODE_DELEGATION_NS_SERVFAIL_SOA_EXISTS,
    PIPELINE_RESULT_CODE_DELEGATION_NXDOMAIN,
    PIPELINE_RESULT_CODE_DELEGATION_SERVFAIL,
    PIPELINE_RESULT_CODE_DELEGATION_TIMEOUT,
)

_RESULT_CODE_BY_STATUS = {
    "exists": PIPELINE_RESULT_CODE_DELEGATION_EXISTS,
    "nxdomain": PIPELINE_RESULT_CODE_DELEGATION_NXDOMAIN,
    "ns_nodata_soa_exists": PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_EXISTS,
    "ns_nodata_soa_absent": PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_ABSENT,
    "ns_nodata_soa_timeout": PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_TIMEOUT,
    "ns_nodata_soa_servfail": PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA_SOA_SERVFAIL,
    "ns_servfail_soa_exists": PIPELINE_RESULT_CODE_DELEGATION_NS_SERVFAIL_SOA_EXISTS,
    "nodata": PIPELINE_RESULT_CODE_DELEGATION_NODATA,
    "no_nameservers": PIPELINE_RESULT_CODE_DELEGATION_NO_NAMESERVERS,
    "timeout": PIPELINE_RESULT_CODE_DELEGATION_TIMEOUT,
}


def classify_delegation(result: Any) -> str:
    """Return the pipeline result code for one delegation result."""
    return _RESULT_CODE_BY_STATUS.get(
        str(result.status), PIPELINE_RESULT_CODE_DELEGATION_SERVFAIL
    )


__all__ = ["classify_delegation"]
