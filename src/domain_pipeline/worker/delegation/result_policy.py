"""Delegation decision reason-code policy helpers."""

from __future__ import annotations

from typing import Any

from domain_pipeline.worker.delegation.reason_codes import (
    DECISION_REASON_CODE_DELEGATION_NS_EMPTY_ANSWER,
    DECISION_REASON_CODE_DELEGATION_NS_LOOKUP_ERROR,
    DECISION_REASON_CODE_DELEGATION_NS_NODATA,
    DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_ABSENT,
    DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_EXISTS,
    DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_INCONCLUSIVE,
    DECISION_REASON_CODE_DELEGATION_NS_RECORDS_EXIST,
    DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_ABSENT,
    DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_EXISTS,
    DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_INCONCLUSIVE,
)

_REASON_CODE_BY_STATUS = {
    "ns_records_exist": DECISION_REASON_CODE_DELEGATION_NS_RECORDS_EXIST,
    "ns_nodata": DECISION_REASON_CODE_DELEGATION_NS_NODATA,
    "ns_nxdomain_soa_exists": DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_EXISTS,
    "ns_nxdomain_soa_absent": DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_ABSENT,
    "ns_nxdomain_soa_inconclusive": (
        DECISION_REASON_CODE_DELEGATION_NS_NXDOMAIN_SOA_INCONCLUSIVE
    ),
    "ns_retry_exhausted_soa_exists": (
        DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_EXISTS
    ),
    "ns_retry_exhausted_soa_absent": (
        DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_ABSENT
    ),
    "ns_retry_exhausted_soa_inconclusive": (
        DECISION_REASON_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_INCONCLUSIVE
    ),
    "ns_empty_answer": DECISION_REASON_CODE_DELEGATION_NS_EMPTY_ANSWER,
    "ns_lookup_error": DECISION_REASON_CODE_DELEGATION_NS_LOOKUP_ERROR,
}


def delegation_reason_code(result: Any) -> str:
    """Return the decision reason code for one delegation result."""
    return _REASON_CODE_BY_STATUS.get(
        str(result.status), DECISION_REASON_CODE_DELEGATION_NS_LOOKUP_ERROR
    )


__all__ = ["delegation_reason_code"]
