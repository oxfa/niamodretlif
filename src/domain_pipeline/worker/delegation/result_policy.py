"""Delegation result-code policy helpers."""

from __future__ import annotations

from typing import Any

from domain_pipeline.worker.delegation.result_codes import (
    PIPELINE_RESULT_CODE_DELEGATION_NS_EMPTY_ANSWER,
    PIPELINE_RESULT_CODE_DELEGATION_NS_LOOKUP_ERROR,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_ABSENT,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_EXISTS,
    PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_INCONCLUSIVE,
    PIPELINE_RESULT_CODE_DELEGATION_NS_RECORDS_EXIST,
    PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_ABSENT,
    PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_EXISTS,
    PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_INCONCLUSIVE,
)

_RESULT_CODE_BY_STATUS = {
    "ns_records_exist": PIPELINE_RESULT_CODE_DELEGATION_NS_RECORDS_EXIST,
    "ns_nodata": PIPELINE_RESULT_CODE_DELEGATION_NS_NODATA,
    "ns_nxdomain_soa_exists": PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_EXISTS,
    "ns_nxdomain_soa_absent": PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_ABSENT,
    "ns_nxdomain_soa_inconclusive": (
        PIPELINE_RESULT_CODE_DELEGATION_NS_NXDOMAIN_SOA_INCONCLUSIVE
    ),
    "ns_retry_exhausted_soa_exists": (
        PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_EXISTS
    ),
    "ns_retry_exhausted_soa_absent": (
        PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_ABSENT
    ),
    "ns_retry_exhausted_soa_inconclusive": (
        PIPELINE_RESULT_CODE_DELEGATION_NS_RETRY_EXHAUSTED_SOA_INCONCLUSIVE
    ),
    "ns_empty_answer": PIPELINE_RESULT_CODE_DELEGATION_NS_EMPTY_ANSWER,
    "ns_lookup_error": PIPELINE_RESULT_CODE_DELEGATION_NS_LOOKUP_ERROR,
}


def classify_delegation(result: Any) -> str:
    """Return the pipeline result code for one delegation result."""
    return _RESULT_CODE_BY_STATUS.get(
        str(result.status), PIPELINE_RESULT_CODE_DELEGATION_NS_LOOKUP_ERROR
    )


__all__ = ["classify_delegation"]
